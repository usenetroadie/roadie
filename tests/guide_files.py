"""The configuration files shown in docs/manual-setup.md, made by roadie's own renderers.

The guide builds the same server by hand. Its files must not drift away from what roadie
writes, so they are generated here (with placeholders instead of secrets) and
tests/test_guide.py fails when the guide and roadie differ. Update the guide with:

    ROADIE_UPDATE_GUIDE=1 python3 -m unittest tests.test_guide
"""

import json
import re
from pathlib import Path

from roadie.answers import Answers
from roadie.render import build_render_config, load_versions
from roadie.render import authelia, compose, envfiles, system, traefik
from roadie.render.yaml import dump

ROOT = Path(__file__).parent.parent
GUIDE = ROOT / "docs/manual-setup.md"
STACK = "/opt/stack"  # the guide's folder (roadie uses /opt/roadie/stack)
DOMAIN = "example.com"
# placeholders the guide replaces with real values; letters, digits and _ only (safe in env files)
SECRETS = {
    "aiostreams_secret_key": "YOUR_AIOSTREAMS_SECRET_KEY",
    "aiostreams_admin_password": "YOUR_AIOSTREAMS_ADMIN_PASSWORD",
    "aiostreams_playback_password": "YOUR_AIOSTREAMS_PLAYBACK_PASSWORD",
    "prowlarr_api_key": "YOUR_PROWLARR_API_KEY",
    "authelia_jwt_secret": "", "authelia_session_secret": "", "authelia_storage_key": "",
    "aiometadata_addon_password": "YOUR_AIOMETADATA_ADDON_PASSWORD",
}
PROVIDERS = [{"host": "news.example.com", "port": 563, "tls": True, "username": "YOUR_USENET_USER",
              "password": "YOUR_USENET_PASSWORD", "connections": 20, "role": "primary"}]
PASSWORD_HASH = "$argon2id$v=19$m=65536,t=3,p=4$YOUR_PASSWORD_HASH"


def _config():
    data = json.loads((ROOT / "examples/answers.example.json").read_text())
    data.pop("duckdns")
    data.update(domain=DOMAIN, admin_user="streamadmin", auth={"username": "you", "password": "x" * 16})
    cfg = build_render_config(Answers.from_dict(data), load_versions(), mem_mb=4000, disk_gb=50, tz="UTC")
    cfg.metadata = True  # the guide shows AIOMetadata as an optional part
    return cfg


def _clean(text: str) -> str:
    """No roadie header (nothing overwrites the reader's files), the guide's folder, no status page."""
    lines = [line for line in text.splitlines() if "Generated by roadie" not in line]
    return "\n".join(lines).lstrip("\n").replace("/opt/roadie/stack", STACK) + "\n"


def files() -> dict[str, str]:
    """name in the guide -> content."""
    cfg = _config()
    out = {}

    services = compose.compose_dict(cfg)
    services["services"].pop("status")  # the status page needs roadie's watcher
    services["name"] = "stack"
    out["compose.yaml"] = dump(services).replace('"roadie"', '"stack"').replace("  roadie:", "  stack:")

    routes = traefik.dynamic_dict(cfg)
    for part in ("routers", "services"):
        routes["http"][part].pop("status")
    for f in traefik.render_traefik(cfg):
        if f.path.endswith("traefik.yml"):
            out["config/traefik/traefik.yml"] = _clean(f.content)
    out["config/traefik/routes.yml"] = dump(routes)

    auth = authelia.config_dict(cfg)
    rule = auth["access_control"]["rules"][-1]
    rule["domain"] = [d for d in rule["domain"] if not d.startswith("status.")]
    out["config/authelia/configuration.yml"] = dump(auth)
    for f in authelia.render_authelia(cfg, SECRETS, PASSWORD_HASH):
        if f.path in ("config/authelia/users.yml", "env/authelia.env"):
            out[f.path] = _clean(f.content)

    for f in envfiles.render_env(cfg, SECRETS, PROVIDERS, "YOUR_TMDB_API_KEY"):
        out[f.path] = _clean(f.content.replace("# Generated by roadie. Contains secrets - keep private.\n", ""))

    out["/etc/ssh/sshd_config.d/01-hardening.conf"] = _clean(system.sshd_dropin(cfg).content)
    for f in system.fail2ban_files(cfg, ignore_ips=(), ssh_ports=(22,)):
        out[f.path.replace("roadie", "stack")] = _clean(f.content).replace("roadie-", "stack-").replace(
            "# loopback and the addresses the admin used for the wizard are never banned",
            "# never banned: the server itself (add your own IP address here if it never changes)")
    out["/etc/apt/apt.conf.d/99zz-auto-updates"] = _clean(system.unattended_upgrades(cfg).content)
    return out


BLOCK = re.compile(r"(<!-- file: (?P<name>\S+) -->\n```[a-z]*\n)(?P<body>.*?)(```)", re.S)


def blocks(text: str) -> dict[str, str]:
    return {m.group("name"): m.group("body") for m in BLOCK.finditer(text)}


def update(text: str) -> str:
    made = files()
    return BLOCK.sub(lambda m: m.group(1) + made[m.group("name")] + m.group(4), text)
