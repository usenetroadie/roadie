import io
import tempfile
import time
import unittest
from pathlib import Path

from roadie import guard
from roadie.engine import Context
from roadie.paths import Paths
from roadie.redact import Redactor
from roadie.render import HEADER, RenderedFile
from roadie.secretstore import SecretStore
from roadie.state import State
from roadie.ui import Prompter

OLD_HEAD = "# Generated by roadie. Changes are overwritten when the wizard runs again.\n"
NEW_HEAD = "".join(f"# {line}\n" for line in HEADER.splitlines())


class GuardTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        paths = Paths(Path(tmp.name))
        self.ctx = Context(paths=paths, state=State(paths.state_file), secrets=SecretStore(paths.secrets_file),
                           ui=Prompter(inp=io.StringIO(""), out=io.StringIO()), redact=Redactor())
        self.base = paths.stack_dir
        self.today = time.strftime("%Y%m%d")

    def write(self, content, path="config/a.yml", mode=0o644):
        guard.write_guarded(self.ctx, [RenderedFile(path, content, mode)], self.base)

    def copies(self):
        return self.ctx.extra.get("mine_copies", [])

    def test_hand_edit_makes_copy(self):
        self.write("a: 1\n")
        (self.base / "config/a.yml").write_text("a: 1\nmine: yes\n")
        self.write("a: 2\n")
        copy = self.base / f"config/a.yml.mine-{self.today}.bak"
        self.assertEqual(copy.read_text(), "a: 1\nmine: yes\n")
        self.assertEqual((self.base / "config/a.yml").read_text(), "a: 2\n")
        self.assertEqual(self.copies(), [("config/a.yml", str(copy))])

    def test_unchanged_file_no_copy(self):
        self.write("a: 1\n")
        self.write("a: 2\n")  # roadie's own change: nobody touched the file
        self.write("a: 2\n")
        self.assertEqual(self.copies(), [])
        self.assertEqual((self.base / "config/a.yml").read_text(), "a: 2\n")
        self.assertEqual(list((self.base / "config").iterdir()), [self.base / "config/a.yml"])
        self.assertIn("config/a.yml", self.ctx.state.answers["_written"])

    def test_first_run_without_record_copies_only_if_different(self):
        target = self.base / "config/a.yml"
        target.parent.mkdir(parents=True)
        target.write_text(OLD_HEAD + "a: 1\n")  # written by an older roadie: only the header differs
        self.write(NEW_HEAD + "a: 1\n")
        self.assertEqual(self.copies(), [])
        self.assertEqual(target.read_text(), NEW_HEAD + "a: 1\n")

        other = self.base / "config/b.yml"
        other.write_text(OLD_HEAD + "a: 1\nmine: yes\n")
        self.write(NEW_HEAD + "a: 1\n", path="config/b.yml")
        self.assertEqual(self.copies(), [("config/b.yml", str(self.base / f"config/b.yml.mine-{self.today}.bak"))])

    def test_copy_without_record_marked_unsure(self):
        other = self.base / "config/b.yml"
        other.parent.mkdir(parents=True)
        other.write_text("a: 1\nmine: yes\n")  # no record: roadie cannot tell who changed it
        self.write("a: 1\n", path="config/b.yml")
        (copy,) = [c for _, c in self.copies()]
        self.assertEqual(self.ctx.extra["unsure_copies"], {copy})
        other.write_text("a: 1\nmine: again\n")  # now a record exists: a real hand edit
        self.write("a: 2\n", path="config/b.yml")
        self.assertEqual(self.ctx.extra["unsure_copies"], {copy})
        self.assertEqual(len(self.copies()), 2)

    def test_copy_keeps_mode_0600(self):
        self.write("SECRET=1\n", path="env/x.env", mode=0o600)
        (self.base / "env/x.env").write_text("SECRET=2\n")
        self.write("SECRET=3\n", path="env/x.env", mode=0o600)
        copy = Path(self.copies()[0][1])
        self.assertEqual(copy.stat().st_mode & 0o777, 0o600)

    def test_second_copy_same_day_gets_suffix(self):
        self.write("a: 1\n")
        for n, text in enumerate(["x\n", "y\n", "z\n"]):
            (self.base / "config/a.yml").write_text(text)
            self.write(f"a: {n + 2}\n")
        names = [Path(c).name for _, c in self.copies()]
        self.assertEqual(names, [f"a.yml.mine-{self.today}.bak", f"a.yml.mine-{self.today}-2.bak",
                                 f"a.yml.mine-{self.today}-3.bak"])
        self.assertEqual(Path(self.copies()[2][1]).read_text(), "z\n")

    def test_secrets_not_copied_when_equal(self):
        target = self.base / "env/x.env"
        target.parent.mkdir(parents=True)
        target.write_text("SECRET=1\n")  # no record yet, same content
        target.chmod(0o600)
        before = target.stat().st_mtime_ns
        self.write("SECRET=1\n", path="env/x.env", mode=0o600)
        self.assertEqual(self.copies(), [])
        self.assertEqual(sorted(p.name for p in target.parent.iterdir()), ["x.env"])
        self.assertEqual(target.stat().st_mtime_ns, before)  # same content: not rewritten

    def test_env_file_with_old_header_is_not_copied(self):
        from roadie.render import envfiles
        new = envfiles._env({"A": "1"})
        target = self.base / "env/x.env"
        target.parent.mkdir(parents=True)
        target.write_text("# Generated by roadie. Contains secrets - keep private.\nA=1\n")  # older roadie
        self.write(new, path="env/x.env", mode=0o600)
        self.assertEqual(self.copies(), [])
        self.assertEqual(target.read_text(), new)

    def test_absolute_paths_go_under_root(self):
        self.write("x\n", path="/etc/roadie-test.conf")
        self.assertEqual((self.ctx.paths.root / "etc/roadie-test.conf").read_text(), "x\n")

    def test_record_is_saved_with_state(self):
        self.write("a: 1\n")
        self.ctx.state.save()
        self.assertIn("config/a.yml", State(self.ctx.paths.state_file).answers["_written"])


if __name__ == "__main__":
    unittest.main()
