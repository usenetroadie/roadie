"""Operations steps: push messages, backup key, timers for watcher and backups, login status."""

import re
import time
from pathlib import Path

from roadie import notify, system
from roadie.engine import Context, Outcome, Step
from roadie.i18n import t
from roadie.ops.common import Env
from roadie.paths import atomic_write

BIN = "/usr/local/bin/roadie"


def _unit(description: str, command: str) -> str:
    return (f"[Unit]\nDescription=roadie: {description}\nAfter=network-online.target docker.service\n\n"
            f"[Service]\nType=oneshot\nExecStart={BIN} {command}\n")


def _timer(description: str, schedule: str) -> str:
    return (f"[Unit]\nDescription=roadie: {description}\n\n[Timer]\n{schedule}\nPersistent=true\n\n"
            "[Install]\nWantedBy=timers.target\n")


UNITS = {
    "roadie-watch.service": _unit("server watcher", "watch"),
    "roadie-watch.timer": _timer("server watcher every 5 minutes", "OnBootSec=3min\nOnUnitActiveSec=5min"),
    "roadie-backup.service": _unit("encrypted backup", "backup --quiet"),
    "roadie-backup.timer": _timer("weekly encrypted backup",
                                        "OnCalendar=Sun *-*-* 04:07:00\nRandomizedDelaySec=20min"),
    "roadie-report.service": _unit("weekly report", "report"),
    "roadie-report.timer": _timer("weekly report as a push message", "OnCalendar=Sun *-*-* 10:13:00"),
}
MOTD = f"#!/bin/sh\n# Generated by roadie: short status at login\n{BIN} status --motd 2>/dev/null || true\n"


QUIET_MOTD = ["10-help-text", "50-motd-news", "90-updates-available", "91-contract-ua-esm-status",
              "91-release-upgrade"]


def quiet_ubuntu_motd(root: Path) -> None:
    """Hide Ubuntu's own login noise so the roadie hint is the one thing a beginner reads."""
    for name in QUIET_MOTD:
        part = root / "etc/update-motd.d" / name
        if part.exists():
            part.chmod(part.stat().st_mode & ~0o111)
    conf = root / "etc/default/motd-news"
    if conf.exists():
        text = conf.read_text()
        new = re.sub(r"(?m)^ENABLED=.*$", "ENABLED=0", text) if re.search(r"(?m)^ENABLED=", text) \
            else text + "ENABLED=0\n"
        if new != text:
            conf.write_text(new)


def _env(ctx: Context) -> Env:
    return Env(ctx.paths, ctx.state, ctx.secrets)


MAX_RESENDS = 3
WAIT_SECONDS = 8


def notifications(ctx: Context, sleep=time.sleep) -> Outcome | None:
    topic = ctx.secrets.generate("ntfy_topic", 20)
    ctx.redact.add(topic)
    server = (ctx.answers.data.get("notify") or {}).get("ntfy_url") or notify.DEFAULT_SERVER
    ui = ctx.ui
    ui.heading(t("ops.push.heading"))
    send = lambda: _env(ctx).push(t("ops.push.test_title"), t("ops.push.test_body"))
    failed = Outcome("warn", note=t("ops.push.note_failed"))
    if not ctx.extra.get("interactive"):
        ui.info(t("ops.push.where", file=str(ctx.paths.secrets_file)))
        if not send():
            ui.warn(t("ops.push.failed"))
            return failed
        return None
    ui.info(t("ops.push.help"))
    ui.copyable(topic)
    if server.rstrip("/") != notify.DEFAULT_SERVER.rstrip("/"):
        ui.info(t("ops.push.own_server", server=server))
    ui.info(t("ops.push.secret"))
    later = Outcome("ok", note=t("ops.push.note_later"))
    if ui.choose(t("ops.push.subscribed"), [("yes", t("ops.push.subscribed_yes")),
                                            ("later", t("ops.push.subscribed_later"))]) == "later":
        return later
    for attempt in range(MAX_RESENDS + 1):
        if not send():
            ui.warn(t("ops.push.failed"))
            return failed
        ui.ok(t("ops.push.sent"))
        ui.countdown(WAIT_SECONDS, "ops.push.waiting", sleep=sleep)
        last = attempt == MAX_RESENDS  # no resend left: do not offer one
        options = [("yes", t("ops.push.arrived_yes"))] + ([] if last else [("again", t("ops.push.arrived_again"))])
        answer = ui.choose(t("ops.push.arrived"), options + [("later", t("ops.push.arrived_later"))])
        if answer == "yes":
            return Outcome("ok", note=t("ops.push.note_ok"))
        if last:
            break
        if answer == "later":
            return later
        ui.hint(t("ops.push.tips", server=server))
    return Outcome("ok", note=t("ops.push.note_unconfirmed"))


def backup_key(ctx: Context) -> None:
    """Without a key from the user, create a pair: the public half stays here, the private
    half is shown once and never stored on the server."""
    if (ctx.answers.data.get("backup") or {}).get("age_recipient") or ctx.state.answers.get("_age_recipient"):
        return
    if not ctx.extra.get("interactive"):
        ctx.ui.warn(t("ops.backup.no_key"))
        return
    out = system.run(["age-keygen"])
    private = next(line for line in out.splitlines() if line.startswith("AGE-SECRET-KEY-"))
    public = next(line.split(": ", 1)[1] for line in out.splitlines() if "public key:" in line)
    ctx.redact.add(private)
    ctx.ui.alert(t("ops.backup.key_heading"))
    ctx.ui.info(t("ops.backup.key_help"))
    ctx.ui.copyable(private)
    while not ctx.ui.confirm(t("ops.backup.key_saved"), default=False):
        ctx.ui.copyable(private)
    ctx.ui.offer_clear()
    ctx.state.answers["_age_recipient"] = public
    ctx.state.save()


def maintenance(ctx: Context) -> None:
    for name, content in UNITS.items():
        atomic_write(Path("/etc/systemd/system") / name, content, 0o644)
    atomic_write(Path("/etc/update-motd.d/60-roadie"), MOTD, 0o755)
    quiet_ubuntu_motd(ctx.paths.root)
    (ctx.paths.root / "var/lib/roadie").mkdir(mode=0o700, parents=True, exist_ok=True)
    system.run(["systemctl", "daemon-reload"])
    system.run(["systemctl", "enable", "--now", "roadie-watch.timer", "roadie-backup.timer",
                "roadie-report.timer"])


def steps() -> list[Step]:
    return [
        Step("notifications", "step.notifications", notifications),
        Step("backup_key", "step.backup_key", backup_key, always=True),
        Step("maintenance", "step.maintenance", maintenance, always=True,
             verify=lambda c: system.ok(["systemctl", "is-active", "--quiet", "roadie-watch.timer"])),
    ]
