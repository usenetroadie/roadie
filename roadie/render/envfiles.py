"""Env files for AIOStreams and Prowlarr (mode 0600). Instance-wide AIOStreams settings are
set here via its documented env variables - never written into its database."""

import json
import re

from roadie.render import OWN_CHANGES, RenderConfig, RenderedFile

GIB = 1024 ** 3
# NZB downloads and indexer searches look like a normal browser, not like "AIOStreams/x.y"
# (some indexers treat unknown clients worse). Single quotes: compose takes the value literally.
REQUEST_HEADER_OVERRIDES = "'[nzb_grabs]:{chrome},[newznab]:{chrome}'"
ADMIN, PLAYBACK = "admin", "playback"
_SAFE = re.compile(r"^[A-Za-z0-9_.:/@=,|+-]*$")  # compose interpolates $ and treats # specially


def cache_sizes(disk_gb: float) -> tuple[int, int]:
    """(usenet segment cache, NZB cache) in bytes, scaled to the disk size."""
    segment = min(20, max(2, int(disk_gb * 0.2)))
    nzb = 1 if disk_gb < 40 else 2 if disk_gb < 200 else 5
    return segment * GIB, nzb * GIB


def _json_value(obj) -> str:
    """JSON in single quotes; characters that env-file parsers treat specially are written
    as JSON unicode escapes, so any password survives unchanged."""
    text = json.dumps(obj, separators=(",", ":"))
    for ch in ("$", "'", "#", "`"):
        text = text.replace(ch, f"\\u{ord(ch):04x}")
    return f"'{text}'"


def usenet_providers(providers: list[dict]) -> list[dict]:
    """Answer format -> AIOStreams USENET_PROVIDERS format (primary first)."""
    ordered = sorted(providers, key=lambda p: p["role"] != "primary")
    out = []
    for i, p in enumerate(ordered, 1):
        entry = {"id": f"provider{i}", "name": p["host"], "host": p["host"], "port": p["port"], "tls": p["tls"],
                 "username": p["username"], "password": p["password"], "maxConnections": p["connections"],
                 "priority": i}
        if p["role"] == "backup":
            entry["isBackup"] = True
        out.append(entry)
    return out


ENV_HEADER = "# Generated by roadie. Contains secrets - keep private."


def _env(values: dict, raw: dict | None = None) -> str:
    lines = [ENV_HEADER, f"# {OWN_CHANGES}"]
    for key, value in (raw or {}).items():
        lines.append(f"{key}={value}")
    for key, value in values.items():
        value = str(value)
        if not _SAFE.match(value):
            raise ValueError(f"unsafe characters in value of {key}")
        lines.append(f"{key}={value}")
    return "\n".join(lines) + "\n"


def metadata_env(cfg: RenderConfig, secrets: dict, tmdb_key: str) -> RenderedFile:
    """AIOMetadata: one server-wide TMDB key, a password for creating configs, and no
    background warm-up (it would keep a small server busy for hours)."""
    return RenderedFile("env/aiometadata.env", _env({
        "PORT": 3232,
        "HOST_NAME": f"https://{cfg.host('metadata')}",
        "NODE_ENV": "production",
        "LOG_LEVEL": "info",
        "DATABASE_URI": "sqlite://addon/data/db.sqlite",
        "REDIS_URL": "redis://aiometadata-redis:6379",
        "BUILT_IN_TMDB_API_KEY": tmdb_key,
        "ADDON_PASSWORD": secrets["aiometadata_addon_password"],
        "ENABLE_CACHE_WARMING": "false",
        "CACHE_WARMUP_ON_STARTUP": "false",
        "TMDB_POPULAR_WARMING_ENABLED": "false",
        "MAL_WARMUP_ENABLED": "false",
    }), 0o600)


def render_env(cfg: RenderConfig, secrets: dict, providers: list[dict] | None = None,
               tmdb_key: str | None = None) -> list[RenderedFile]:
    segment, nzb = cache_sizes(cfg.disk_gb)
    aio = {
        "BASE_URL": f"https://{cfg.host('aiostreams')}",
        "SECRET_KEY": secrets["aiostreams_secret_key"],
        "DATABASE_URI": "sqlite://./data/db.sqlite",
        "AIOSTREAMS_AUTH": f"{ADMIN}:{secrets['aiostreams_admin_password']},"
                           f"{PLAYBACK}:{secrets['aiostreams_playback_password']}",
        "AIOSTREAMS_AUTH_PERMISSIONS": f"{ADMIN}=admin,{PLAYBACK}=service|proxy",
        "CATALOG_CACHE_TTL": 86400,
        "META_CACHE_TTL": 86400,
        "USENET_SEGMENT_DISK_CACHE_BYTES": segment,
        "BUILTIN_NZB_GRAB_DISK_CACHE_BYTES": nzb,
        "REGEX_FILTER_ACCESS": "all",  # private single-user instance behind the login
    }
    raw = {"REQUEST_HEADER_OVERRIDES": REQUEST_HEADER_OVERRIDES}
    if providers:
        raw["USENET_PROVIDERS"] = _json_value(usenet_providers(providers))
    if cfg.mem_mb < 3800:
        aio["USENET_PERFORMANCE_PROFILE"] = "conservative"
    if cfg.metadata:  # catalogs changed in the own AIOMetadata show up within 15 minutes, not 6 hours
        aio["MANIFEST_CACHE_TTL"] = 900
    aio["BUILTIN_PROWLARR_URL"] = "http://prowlarr:9696"
    aio["BUILTIN_PROWLARR_API_KEY"] = secrets["prowlarr_api_key"]
    files = [RenderedFile("env/aiostreams.env", _env(aio, raw), 0o600),
             RenderedFile("env/prowlarr.env", _env({
                 "PROWLARR__AUTH__APIKEY": secrets["prowlarr_api_key"],
                 "PROWLARR__AUTH__METHOD": "External",  # login is handled by Authelia
             }), 0o600)]
    if cfg.metadata:
        files.append(metadata_env(cfg, secrets, tmdb_key))
    return files
