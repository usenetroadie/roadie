"""Pure renderers: answers + versions in, file contents out. Nothing here touches the system."""

import json
from dataclasses import dataclass
from importlib import resources

HEADER = "Generated by roadie. Changes are overwritten when the wizard runs again."


@dataclass
class RenderedFile:
    path: str  # relative to the stack dir, or absolute for system files
    content: str
    mode: int = 0o644


@dataclass
class RenderConfig:
    domain: str  # e.g. example.duckdns.org
    admin_user: str
    auth_username: str
    images: dict  # component -> "image:tag"
    mem_mb: int
    disk_gb: float
    tz: str = "UTC"
    reboot_time: str = "05:00"
    ipv6: bool = False
    test_mode: bool = False  # automated tests: self-signed certificate, no DuckDNS

    def host(self, name: str) -> str:
        return f"{name}.{self.domain}"


def load_versions() -> dict:
    text = resources.files("roadie").joinpath("data/versions.json").read_text("utf-8")
    return json.loads(text)["components"]


def build_render_config(answers, versions: dict, mem_mb: int, disk_gb: float, tz: str = "UTC") -> RenderConfig:
    d = answers.data
    return RenderConfig(
        domain=f"{d['duckdns']['subdomain']}.duckdns.org",
        admin_user=d["admin_user"],
        auth_username=d["auth"]["username"],
        images={k: f"{v['image']}:{v['tag']}" for k, v in versions.items()},
        mem_mb=mem_mb,
        disk_gb=disk_gb,
        tz=tz,
        reboot_time=d["maintenance"]["reboot_time"],
    )
